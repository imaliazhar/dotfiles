#!/bin/bash
# Generate aerospace.toml from base.toml plus a monitors/<mode>.toml workspace-to-monitor assignment.
# Usage: aerospace-monitor-toggle.sh [built-in|external|gaming]
# Without an argument, toggles built-in -> external, anything else -> built-in.

DIR="$HOME/.config/aerospace"
CONFIG="$DIR/aerospace.toml"

current=$(sed -n 's/^# monitor-mode: //p' "$CONFIG" 2>/dev/null)

mode="$1"
if [ -z "$mode" ]; then
    if [ "$current" = "built-in" ]; then mode="external"; else mode="built-in"; fi
fi

if [ ! -f "$DIR/monitors/$mode.toml" ]; then
    echo "Unknown mode: $mode" >&2
    exit 1
fi

{
    echo "# Generated by scripts/aerospace-monitor-toggle.sh from base.toml and monitors/$mode.toml, edit those instead"
    echo "# monitor-mode: $mode"
    echo
    cat "$DIR/base.toml"
    echo
    cat "$DIR/monitors/$mode.toml"
} > "$CONFIG"

echo "Switched to $mode monitor mode"

if pgrep -xq AeroSpace; then
    aerospace reload-config
fi
